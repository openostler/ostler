"""The VSS namespace seam (ADR-0016, specs/2026-10-06-u0-seams-design.md §A).

``src/openostler/metrics.json`` and ``vss_leaves.json`` are generated by
``tools/build_metrics.py`` from ``vss/ostler.vspec`` over the pinned release in
``vss/upstream/``. These tests check the committed files and the ``metric`` key on signal
store records. The freshness check needs vss-tools (dev-only, Python >= 3.11); CI
installs it and also runs ``python tools/build_metrics.py --check``.
"""
from __future__ import annotations

import importlib.util
import json
import re
from pathlib import Path

import pytest

from openostler import metrics, signals
from openostler.metrics import PATH_RE, is_known, load_metrics, metric_info, vss_version
from tests.fake_pack import FAKE_PACK

ROOT = Path(__file__).resolve().parents[1]
UPSTREAM = ROOT / "vss" / "upstream"
HAS_VSS_TOOLS = importlib.util.find_spec("vss_tools") is not None


def _unit_keys() -> "set[str]":
    """Top-level keys of the pinned units.yaml (stdlib parse: one ``key:`` per line)."""
    keys = set()
    for line in (UPSTREAM / "units.yaml").read_text(encoding="utf-8").splitlines():
        m = re.match(r"^([^\s#][^:]*):\s*$", line)
        if m:
            keys.add(m.group(1).strip().strip("'\""))
    return keys


def _store_records(signals_dir: Path) -> "list[tuple[str, dict]]":
    out = []
    for f in sorted(Path(signals_dir).glob("*.json")):
        for r in json.loads(f.read_text(encoding="utf-8")):
            out.append((f"{f.stem}.{r.get('name')}", r))
    return out


# ---- the pin and the vendored release ------------------------------------------------ #

def test_vss_pin_is_6_1():
    assert (ROOT / "vss" / "VERSION").read_text(encoding="utf-8").strip() == "6.1"
    assert vss_version() == "6.1"
    assert json.loads(metrics.LEAVES_FILE.read_text(encoding="utf-8"))["vss_version"] == "6.1"


def test_vendored_release_files_are_present_with_their_licence():
    for name in ("vss.json", "model.vspec", "units.yaml", "quantities.yaml", "LICENSE",
                 "README.md"):
        assert (UPSTREAM / name).is_file(), name
    assert "Mozilla Public License Version 2.0" in (UPSTREAM / "LICENSE").read_text(encoding="utf-8")
    size = sum(p.stat().st_size for p in UPSTREAM.iterdir())
    assert size < 5 * 1024 * 1024


def test_units_parse_matches_yaml_when_available():
    yaml = pytest.importorskip("yaml", reason="PyYAML comes with vss-tools (dev-only)")
    assert _unit_keys() == set(yaml.safe_load((UPSTREAM / "units.yaml").read_text(encoding="utf-8")))


